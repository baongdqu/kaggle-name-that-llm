        "        self.encoder = AutoModel.from_pretrained(encoder_path, config=self.config)\n",
        "        # Gradient checkpointing to save VRAM and allow batch size 32\n",
        "        self.encoder.gradient_checkpointing_enable()\n",
        "        self.classifier = nn.Linear(self.config.hidden_size, num_classes)\n",
        "        \n",
